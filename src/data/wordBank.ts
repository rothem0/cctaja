// Helper to create word item with automatic initials
function createWord(
  id: string,
  word: string,
  category: string,
  clue: string,
  difficulty: 1 | 2 | 3,
  funFact?: string,
  synonyms?: string[]
): WordItem {
  return {
    id,
    word,
    category,
    clue,
    initials: getInitials(word),
    difficulty,
    funFact,
    synonyms,
  };
}

